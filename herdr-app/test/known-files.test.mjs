// scripts/known-files.mjs: the table of older Flockbook files that the helper build embeds. It reads git history
// and the release tags (CI checks out with fetch-depth 0).
import { test } from "node:test";
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { execFileSync, spawnSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { installed, readTable, writeTable, generate } from "../../scripts/known-files.mjs";

const repo = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const script = join(repo, "scripts", "known-files.mjs");
const sha = (b) => createHash("sha256").update(b).digest("hex");

test("only what the install puts in a home counts", () => {
  for (const p of ["layouts/flockbook.json", "themes/flockbook.json", "mods/flockbook/main.js", "mods/flockbook/icons/gear.svg"]) assert.ok(installed(p), p);
  for (const p of ["layouts/other.json", "keys.json", "mods/other/main.js", "mods/flockbook/.DS_Store", "mods/flockbook/jsconfig.json",
    "mods/flockbook/herdr.d.ts", "themes/sub/x.json", "README.md"]) assert.ok(!installed(p), p);
  // Only at the mod's top level are jsconfig.json and *.d.ts generated by herdr-app.
  assert.ok(installed("mods/flockbook/types/x.d.ts"));
});

test("a table written and read back is the same", () => {
  const t = new Map([[`layouts/flockbook.json\t${"a".repeat(64)}`, "v0.7.0"], [`mods/flockbook/a.js\t${"b".repeat(64)}`, "v0.7.0+main"]]);
  const text = writeTable(t);
  assert.match(text, /^# /);
  assert.deepEqual(readTable(text), t);
});

test("from git: each release from v0.7.0, main between them, and the files as they are now", () => {
  const t = generate();
  const v070 = execFileSync("git", ["show", "v0.7.0:herdr-mod/layouts/flockbook.json"], { cwd: repo });
  assert.equal(t.get(`layouts/flockbook.json\t${sha(v070)}`), "v0.7.0");
  const v080 = execFileSync("git", ["show", "v0.8.0:herdr-app/mods/flockbook/helpercard.js"], { cwd: repo });
  assert.equal(t.get(`mods/flockbook/helpercard.js\t${sha(v080)}`), "v0.8.0");
  for (const p of ["layouts/flockbook.json", "mods/flockbook/main.js", "themes/flockbook.json"]) {
    assert.ok(t.has(`${p}\t${sha(readFileSync(join(repo, "herdr-app", p)))}`), `${p} as it is now`);
  }
  for (const [k, v] of t) {
    const [p, h] = k.split("\t");
    assert.ok(installed(p), p);
    assert.match(h, /^[0-9a-f]{64}$/);
    assert.match(v, /^v\d+\.\d+\.\d+(\+main)?$/);
  }
});

test("the command line: stdout, or --out; anything else is a usage error", () => {
  const out = spawnSync(process.execPath, [script], { cwd: repo, encoding: "utf8" });
  assert.equal(out.status, 0, out.stderr);
  assert.ok(out.stdout.split("\n").filter((l) => l && !l.startsWith("#")).length > 40);
  const bad = spawnSync(process.execPath, [script, "--check"], { cwd: repo, encoding: "utf8" });
  assert.equal(bad.status, 2);
});
